export const translateStatus = (language, value) => {
  const normalized = String(value ?? '').trim().toLowerCase();
  if (!normalized) return value ?? '';
  const key = statusKeys[normalized] || normalized.replace(/[\s-]+([a-z])/g, (_, letter) => letter.toUpperCase());
  return translateMessage(language, `common.status.${key}`, value);
};