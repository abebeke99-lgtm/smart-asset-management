export const translateMessage = (language, key, fallback, values) => {
  const read = (catalog) => key.split('.').reduce((value, segment) => value?.[segment], catalog);
  const message = read(messages[language]) ?? read(messages.en) ?? fallback ?? key;
  if (!values || typeof message !== 'string') return message;
  return message.replace(/\{(\w+)\}/g, (placeholder, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder
  ));
};

export const translateNavigationLabel = (language, label) => {
  const explicitTranslation = messages[language]?.navigation?.labels?.[label];
  if (explicitTranslation !== undefined) return explicitTranslation;

  const commonNavigationKey = Object.entries(messages.en.navigation)
    .find(([, value]) => typeof value === 'string' && value === label)?.[0];
  return commonNavigationKey
    ? translateMessage(language, `navigation.${commonNavigationKey}`, label)
    : label;
};

const statusKeys = {
  'in-use': 'inUse',
  'in use': 'inUse',
  'in-progress': 'inProgress',
  'in progress': 'inProgress',
  'under-maintenance': 'underMaintenance',
  'under maintenance': 'underMaintenance',
  'out-of-service': 'outOfService',
  'out of service': 'outOfService',
  'waiting-for-parts': 'waitingForParts',
  'waiting for parts': 'waitingForParts'
};

export const translateStatus = (language, value) => {
  const normalized = String(value ?? '').trim().toLowerCase();
  if (!normalized) return value ?? '';
  const key = statusKeys[normalized] || normalized.replace(/[\s-]+([a-z])/g, (_, letter) => letter.toUpperCase());
  return translateMessage(language, `common.status.${key}`, value);
};