export const getShellTranslations = (language) => {
  const locale = language === 'am' ? messages.am : messages.en;
  return {
    ...locale.brand,
    ...locale.navigation,
    ...locale.auth,
    ...locale.dashboard,
    ...locale.footer,
    ...locale.appearance,
    ...locale.legal
  };
};

export const translateMessage = (language, key, fallback) => {
  const read = (catalog) => key.split('.').reduce((value, segment) => value?.[segment], catalog);
  return read(messages[language]) ?? read(messages.en) ?? fallback ?? key;
};